/**
 * Regenerates `src/fontData.ts` from the `geist` package's variable fonts.
 * Run after bumping `geist`:  node audio/embed-fonts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const b64 = (p) => fs.readFileSync(path.join(root, p)).toString('base64');

const sans = b64('node_modules/geist/dist/fonts/geist-sans/Geist-Variable.woff2');
const mono = b64('node_modules/geist/dist/fonts/geist-mono/GeistMono-Variable.woff2');

const header = `/**
 * Geist and Geist Mono, base64-inlined from the \`geist\` npm package.
 *
 * Generated by \`node audio/embed-fonts.mjs\` — do not hand-edit.
 *
 * Why inlined rather than fetched from public/: a per-frame render kept stalling
 * on the woff2 request (a delayRender for the font timed out at frame 563), and a
 * font that resolves on 2000 frames but not the 2001st is a broken render. A data
 * URI has nothing to stall on.
 */

`;

fs.writeFileSync(
  path.join(root, 'src/fontData.ts'),
  `${header}export const GEIST_SANS_WOFF2 = '${sans}';\n\nexport const GEIST_MONO_WOFF2 = '${mono}';\n`,
);
console.log('wrote src/fontData.ts');
